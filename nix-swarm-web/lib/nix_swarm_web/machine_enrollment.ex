defmodule NixSwarmWeb.MachineEnrollment do
  @moduledoc """
  Generates safe, copyable Nix snippets for adding a Nix-Swarm machine.

  This module only renders configuration. It never provisions a host, handles a
  cookie, edits a flake, or calls the cluster.
  """

  @hostname_pattern ~r/\A[A-Za-z0-9](?:[A-Za-z0-9.-]*[A-Za-z0-9])?\z/
  @deploy_host_pattern ~r/\A[A-Za-z0-9._-]+@[A-Za-z0-9](?:[A-Za-z0-9._-]*[A-Za-z0-9])?\z/
  @configuration_pattern ~r/\A[A-Za-z_][A-Za-z0-9_-]*\z/
  @interface_pattern ~r/\A[A-Za-z0-9_.-]+\z/
  @peer_pattern ~r/\A[A-Za-z0-9][A-Za-z0-9._-]*@[A-Za-z0-9](?:[A-Za-z0-9._-]*[A-Za-z0-9])?\z/
  @max_hostname_length 253
  @max_deploy_host_length 320
  @max_configuration_length 128
  @max_interface_length 128
  @max_peer_input_length 8_192

  @type result :: %{
          filename: String.t(),
          machine_config: String.t(),
          inventory_snippet: String.t(),
          node_name: String.t(),
          peers: [String.t()]
        }

  @spec generate(map()) :: {:ok, result()} | {:error, [String.t()]}
  def generate(params) when is_map(params) do
    hostname = value(params, "hostname")
    deploy_host = value(params, "deploy_host")
    nixos_configuration = value(params, "nixos_configuration")
    firewall_interface = value(params, "firewall_interface")
    peers = parse_peers(value(params, "peers"))
    node_name = "nix-swarm@#{hostname}"

    errors =
      [
        required_error(hostname, "hostname"),
        length_error(hostname, @max_hostname_length, "hostname"),
        format_error(hostname, @hostname_pattern, "hostname"),
        required_error(deploy_host, "deploy host"),
        length_error(deploy_host, @max_deploy_host_length, "deploy host"),
        format_error(deploy_host, @deploy_host_pattern, "deploy host"),
        required_error(nixos_configuration, "NixOS configuration"),
        length_error(nixos_configuration, @max_configuration_length, "NixOS configuration"),
        format_error(nixos_configuration, @configuration_pattern, "NixOS configuration"),
        required_error(firewall_interface, "private firewall interface"),
        length_error(firewall_interface, @max_interface_length, "private firewall interface"),
        format_error(firewall_interface, @interface_pattern, "private firewall interface"),
        length_error(value(params, "peers"), @max_peer_input_length, "peer list"),
        format_error_for_peers(peers)
      ]
      |> Enum.reject(&is_nil/1)

    if errors == [] do
      peers = (peers ++ [node_name]) |> Enum.uniq() |> Enum.sort()

      {:ok,
       %{
         filename: "machine-#{hostname}.nix",
         machine_config:
           machine_config(
             hostname,
             node_name,
             firewall_interface,
             peers
           ),
         inventory_snippet: inventory_snippet(node_name, deploy_host, nixos_configuration),
         node_name: node_name,
         peers: peers
       }}
    else
      {:error, errors}
    end
  end

  def generate(_params), do: {:error, ["machine details must be a map"]}

  defp value(params, key) do
    params
    |> Map.get(key, "")
    |> to_string()
    |> String.trim()
  end

  defp parse_peers(value) do
    value
    |> String.split(~r/[,\n\r]+/)
    |> Enum.map(&String.trim/1)
    |> Enum.reject(&(&1 == ""))
    |> Enum.uniq()
  end

  defp required_error("", label), do: "#{label} is required"
  defp required_error(_value, _label), do: nil

  defp length_error("", _maximum, _label), do: nil

  defp length_error(value, maximum, label) do
    if String.length(value) <= maximum, do: nil, else: "#{label} is too long"
  end

  defp format_error("", _pattern, _label), do: nil

  defp format_error(value, pattern, label) do
    if Regex.match?(pattern, value), do: nil, else: "#{label} contains unsupported characters"
  end

  defp format_error_for_peers(peers) do
    if Enum.all?(peers, &Regex.match?(@peer_pattern, &1)) do
      nil
    else
      "peer names contain unsupported characters"
    end
  end

  defp machine_config(hostname, node_name, firewall_interface, peers) do
    """
    # Generated by Nix-Swarm. Review the imports and values before applying.
    # This file contains no cluster cookie or deployment credential.
    { ... }:
    {
      imports = [
        ./hardware-configuration.nix
        ../profiles/nix-swarm-node.nix
      ];

      networking.hostName = #{nix_string(hostname)};

      services.nix-swarm = {
        nodeName = #{nix_string(node_name)};
        cookieFile = "/etc/nixos/nix-swarm/secrets/nix-swarm.cookie";
        operatorUsers = [ ];

        peers = [
    #{render_strings(peers)}
        ];

        openFirewall = true;
        firewallInterfaces = [ #{nix_string(firewall_interface)} ];
      };
    }
    """
    |> String.trim()
    |> Kernel.<>("\n")
  end

  defp inventory_snippet(node_name, deploy_host, nixos_configuration) do
    """
    # Add this entry to services.nix-swarm.nodes in the shared cluster module.
    #{nix_string(node_name)} = {
      availability = "active";
      deployHost = #{nix_string(deploy_host)};
      nixosConfiguration = #{nix_string(nixos_configuration)};
    };
    """
    |> String.trim()
    |> Kernel.<>("\n")
  end

  defp render_strings(values) do
    Enum.map_join(values, "\n", fn value -> "      #{nix_string(value)}" end)
  end

  defp nix_string(value) do
    value
    |> String.replace("\\", "\\\\")
    |> String.replace("\"", "\\\"")
    |> then(&"\"#{&1}\"")
  end
end
